function getCombinedProducts() {
  let localProds = [];
  try {
    const stored = localStorage.getItem("eurotex_custom_products");
    if (stored) {
      const parsed = JSON.parse(stored);
      if (Array.isArray(parsed)) localProds = parsed;
    }
  } catch (e) {}

  const map = new Map();

  // 1. Add localStorage custom products first
  (localProds || []).forEach((item) => {
    if (item && item.id) {
      map.set(String(item.id), {
        ...item,
        isCustom: true,
      });
    }
  });

  // 2. Fresh in-memory EUROTEX_PRODUCTS (from MongoDB/Backend) OVERRIDE stale localStorage cache!
  (EUROTEX_PRODUCTS || []).forEach((item) => {
    if (item && item.id) {
      map.set(String(item.id), {
        ...item,
        isCustom:
          item.isCustom === true ||
          String(item.id).startsWith("prod-") ||
          (item.dbId && String(item.dbId).length > 0),
      });
    }
  });

  return Array.from(map.values());
}

function compressBase64Image(dataUrl, maxWidth = 600, quality = 0.65) {
  return new Promise((resolve) => {
    if (!dataUrl || !dataUrl.startsWith("data:image")) return resolve(dataUrl);
    const img = new Image();
    img.onload = () => {
      let width = img.width;
      let height = img.height;
      if (width > maxWidth) {
        height = Math.round((height * maxWidth) / width);
        width = maxWidth;
      }
      const canvas = document.createElement("canvas");
      canvas.width = width;
      canvas.height = height;
      const ctx = canvas.getContext("2d");
      ctx.drawImage(img, 0, 0, width, height);
      resolve(canvas.toDataURL("image/jpeg", quality));
    };
    img.onerror = () => resolve(dataUrl);
    img.src = dataUrl;
  });
}

const EurotexIDB = {
  dbName: "EurotexDB",
  storeName: "products",
  db: null,
  async init() {
    if (this.db) return this.db;
    return new Promise((resolve) => {
      try {
        const req = indexedDB.open(this.dbName, 1);
        req.onupgradeneeded = (e) => {
          const db = e.target.result;
          if (!db.objectStoreNames.contains(this.storeName)) {
            db.createObjectStore(this.storeName);
          }
        };
        req.onsuccess = (e) => {
          this.db = e.target.result;
          resolve(this.db);
        };
        req.onerror = () => resolve(null);
      } catch (err) {
        resolve(null);
      }
    });
  },
  async set(key, val) {
    const db = await this.init();
    if (!db) return;
    return new Promise((resolve) => {
      try {
        const tx = db.transaction(this.storeName, "readwrite");
        const store = tx.objectStore(this.storeName);
        store.put(val, key);
        tx.oncomplete = () => resolve(true);
        tx.onerror = () => resolve(false);
      } catch (err) {
        resolve(false);
      }
    });
  },
  async get(key) {
    const db = await this.init();
    if (!db) return null;
    return new Promise((resolve) => {
      try {
        const tx = db.transaction(this.storeName, "readonly");
        const store = tx.objectStore(this.storeName);
        const req = store.get(key);
        req.onsuccess = () => resolve(req.result);
        req.onerror = () => resolve(null);
      } catch (err) {
        resolve(null);
      }
    });
  },
};

