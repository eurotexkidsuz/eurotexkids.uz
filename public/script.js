//   /product/:id  → Mahsulot sahifasi (Quick View)

function updateURLRoute(path) {
  if (window.location.pathname !== path) {
    history.pushState({ route: path }, document.title, path);
  }
}

function navigateTo(path) {
  history.pushState({ route: path }, document.title, path);
  handleURLRouting();
}

