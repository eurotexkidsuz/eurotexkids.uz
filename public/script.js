function addToCart(
  productId,
  selectedSize = "48",
  selectedColor = "To'q ko'k (Navy)",
) {
  const product = EUROTEX_PRODUCTS.find((p) => p.id === productId);
  if (!product) return;

  const lang = state.currentLang;
  const title = product[`title_${lang}`] || product.title_uz;

  const existing = state.cart.find(
    (c) =>
      c.id === productId &&
      c.size === selectedSize &&
      c.color === selectedColor,
  );
  if (existing) {
    existing.quantity += 1;
  } else {
    state.cart.push({
      id: product.id,
      title: title,
      price: product.price,
      image: product.image,
      nasiyaMonthly: product.nasiyaMonthly,
      size: selectedSize,
      color: selectedColor,
      quantity: 1,
    });
  }

  localStorage.setItem("eurotex_cart", JSON.stringify(state.cart));
  updateCartUI();
  showToast(`"${title.slice(0, 25)}..." savatga qo'shildi 🛒`);
  openCartDrawer();
}

