let _lastProdsHash = "";

async function syncProductsWithBackendAndStorage(isIntervalSync = false) {
  // If this is a background interval tick AND admin is in Admin Panel, pause polling so inputs never reset!
  const isAdminView =
    window.location.pathname.includes("/admin") ||
    state.currentCategory === "admin" ||
    (document.activeElement &&
      document.activeElement.closest("#adminProductsTableContainer")) ||
    (document.getElementById("admin-dashboard-section") &&
      document.getElementById("admin-dashboard-section").style.display !==
        "none");

  if (isIntervalSync && isAdminView) {
    return;
  }

  // Pre-load from IndexedDB immediately so custom products show instantly on refresh!
  try {
    const cachedProds = await EurotexIDB.get("eurotex_custom_products");
    if (Array.isArray(cachedProds) && cachedProds.length > 0) {
      const map = new Map();
      cachedProds.forEach((p) => map.set(String(p.id), p));
      (EUROTEX_PRODUCTS || []).forEach((p) => {
        if (!map.has(String(p.id))) map.set(String(p.id), p);
      });
      EUROTEX_PRODUCTS = Array.from(map.values());
    }
  } catch (e) {}

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2000);
    const res = await fetch("/products", { signal: controller.signal }).catch(() => null);
    clearTimeout(timeoutId);
    if (res && res.ok) {
      const data = await res.json().catch(() => null);
      if (
        data &&
        data.success &&
        Array.isArray(data.products) &&
        data.products.length > 0
      ) {
        const dbProds = data.products.map((p) => ({
          id: p.customId || String(p._id),
          dbId: p._id,
          isCustom: true, // Mark as custom so it pins to top of home grid
          title_uz: p.title_uz,
          title_ru: p.title_ru || p.title_uz,
          title_en: p.title_en || p.title_uz,
          category: normalizeCategory(p.category || "suits"),
          priceUsd: p.priceUsd || 50,
          pachkaPriceUsd: p.pachkaPriceUsd || 45,
          pachkaQty: p.pachkaQty || 6,
          price: p.price || (p.priceUsd || 50) * (state.usdRate || 12650),
          oldPrice:
            p.oldPrice ||
            Math.round((p.priceUsd || 50) * 1.25) * (state.usdRate || 12650),
          image: p.image || "/images/navy_suit.jpg",
          images:
            p.images && p.images.length > 0
              ? p.images
              : [p.image || "/images/navy_suit.jpg"],
          sizes:
            p.sizes && p.sizes.length > 0 ? p.sizes : [46, 48, 50, 52, 54, 56],
          fabric_uz: p.fabric_uz || "Turkiya Premium Jun & Viskoza Blend",
          inStock: p.inStock !== false,
          rating: p.rating || 5.0,
          reviewsCount: p.reviewsCount || 12,
        }));

        const map = new Map();
        // 1. Seed base default products first so product catalog never empties
        DEFAULT_EUROTEX_PRODUCTS.forEach((p) => map.set(String(p.id), p));
        // 2. Overlay DB products from MongoDB Atlas
        dbProds.forEach((p) => {
          const baseItem = map.get(String(p.id)) || {};
          map.set(String(p.id), { ...baseItem, ...p });
        });
        // 3. Overlay local EUROTEX_PRODUCTS so admin edits win & persist
        (EUROTEX_PRODUCTS || []).forEach((p) => {
          if (p && p.id) {
            const dbItem = map.get(String(p.id)) || {};
            map.set(String(p.id), { ...dbItem, ...p });
          }
        });

        EUROTEX_PRODUCTS = Array.from(map.values());
        EurotexIDB.set("eurotex_custom_products", EUROTEX_PRODUCTS);
        try {
          localStorage.removeItem("eurotex_custom_products");
        } catch (err) {}

        // Auto-upload any un-synced local custom products to MongoDB Atlas
        const dbCustomIds = new Set(dbProds.map((p) => String(p.id)));
        EUROTEX_PRODUCTS.forEach((p) => {
          if (p.isCustom && !dbCustomIds.has(String(p.id)) && !p._syncing) {
            p._syncing = true;
            fetch("/products", {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({
                customId: String(p.id),
                title_uz: p.title_uz,
                title_ru: p.title_ru || p.title_uz,
                category: p.category,
                priceUsd: p.priceUsd,
                pachkaPriceUsd: p.pachkaPriceUsd,
                pachkaQty: p.pachkaQty,
                price: p.price,
                oldPrice: p.oldPrice,
                image: p.image,
                images: p.images || [p.image],
                sizes: p.sizes,
                fabric_uz: p.fabric_uz,
                inStock: true,
              }),
            })
              .then(() => {
                delete p._syncing;
              })
              .catch(() => {
                delete p._syncing;
              });
          }
        });
      }
    }
  } catch (err) {
    console.log("Using cached products:", err);
  }

  // Smart Re-render: ONLY re-render if product data actually changed AND admin is not typing!
  const newHash = EUROTEX_PRODUCTS.map(
    (p) => `${p.id}:${p.title_uz}:${p.price}:${p.category}`,
  ).join("|");

  if (newHash !== _lastProdsHash || !isIntervalSync) {
    _lastProdsHash = newHash;
    renderProducts();
    const isTypingInAdmin =
      document.activeElement &&
      document.activeElement.closest("#adminProductsTableContainer");
    if (!isTypingInAdmin) {
      renderAdminProducts();
    }
  }
}

