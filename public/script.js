  if (!val || val < 10 || val > 99) {
    showToast("⚠️ Iltimos 10 dan 99 gacha o'lcham kiriting!");
    input.value = "";
    return;
  }

  const grid = document.getElementById("newProdSizeGrid");
  if (!grid) return;

